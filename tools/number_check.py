#!/usr/bin/env python3
"""Traceable numbers for the manuscript (V8 / V9): fill placeholders and check prose.

NUMBERS_USED.json is generated by the direction's own script from the result files.
Each entry is either a bare number or an object:
  {"mae_holdout_tc281": {"value": 1.339, "fmt": ".2f", "unit": "mm",
                         "source": "results/holdout_metrics.csv#TC281/MAE"},
   "n_sources": 32,
   "_meta": {"generated_by": "code/make_numbers.py", "generated_utc": "..."}}

fill   replace {{key}} or {{key:FMT}} placeholders in a draft with the formatted value;
       an unknown key is an error (nothing is guessed).
check  every numeral in the prose must correspond to a NUMBERS_USED value (same rendered
       string, or equal after rounding to the digits shown). Numerals inside math,
       code, citations, figure/table/equation/section references, DOIs/URLs and years
       (with --allow-years) are ignored. Exit status 1 when any number is untraceable.

Usage:
  number_check.py fill  DRAFT.md --numbers NUMBERS_USED.json [--out OUT.md]
  number_check.py check DRAFT.(md|tex|txt|docx) --numbers NUMBERS_USED.json
                        [--allow 0.3,1e-6] [--allow-years] [--report NUMBER_CHECK.md] [--tol 0]
Standard library only (python-docx is used for .docx when installed).
"""
import argparse
import json
import math
import pathlib
import re
import sys
import zipfile

PLACEHOLDER = re.compile(r"\{\{\s*([A-Za-z_][\w.\-]*)\s*(?::\s*([^}]+))?\}\}")
NUMERAL = re.compile(r"(?<![\w.\-/])[-−+]?\d+(?:[.,]\d+)*(?:\.\d+)?(?:[eE][-+]?\d+)?(?![\w/])")
SKIP_LINE = re.compile(r"^\s*(#|\\section|\\subsection|\\begin\{(equation|align|table|figure)|\\label|\\ref|%)")
REF_CTX = re.compile(r"\b(Fig\.?s?|Figure|Figures|Table|Tables|Eq\.?s?|Equation|Equations|Sect\.?|Section|Sections|Chapter|Appendix|Step|Ref\.?|Refs\.?|Case|Series|Type|Mode|Stage|No\.|Model)\s*\(?\s*$", re.I)
YEAR = re.compile(r"^(19|20)\d\d$")


def load_numbers(path):
    d = json.loads(pathlib.Path(path).read_text(encoding="utf-8"))
    out = {}
    for k, v in d.items():
        if k.startswith("_"):
            continue
        if isinstance(v, dict):
            out[k] = {"value": v.get("value"), "fmt": v.get("fmt"), "unit": v.get("unit"), "source": v.get("source")}
        else:
            out[k] = {"value": v, "fmt": None, "unit": None, "source": None}
    return out


def render(entry, fmt=None):
    v = entry["value"]
    f = fmt or entry.get("fmt")
    if isinstance(v, str):
        return v
    if f:
        try:
            return format(v, f)
        except (ValueError, TypeError):
            return str(v)
    if isinstance(v, float) and v.is_integer():
        return str(int(v))
    return str(v)


def read_text(path):
    p = pathlib.Path(path)
    if p.suffix.lower() == ".docx":
        try:
            import docx
            return "\n".join(par.text for par in docx.Document(str(p)).paragraphs)
        except ImportError:
            xml = zipfile.ZipFile(p).read("word/document.xml").decode("utf8", "replace")
            paras = re.findall(r"<w:p[ >].*?</w:p>", xml, flags=re.S)
            return "\n".join("".join(re.findall(r"<w:t[^>]*>(.*?)</w:t>", q, flags=re.S)) for q in paras)
    return p.read_text(encoding="utf-8", errors="replace")


def strip_protected(text):
    """Blank out fenced code, display/inline math, citations, DOIs and URLs, keeping line structure."""
    def blank(m):
        return re.sub(r"[^\n]", " ", m.group(0))
    text = re.sub(r"```.*?```", blank, text, flags=re.S)
    text = re.sub(r"\$\$.*?\$\$", blank, text, flags=re.S)
    text = re.sub(r"\\\[.*?\\\]", blank, text, flags=re.S)
    text = re.sub(r"\\begin\{(equation|align|eqnarray|gather|multline)\*?\}.*?\\end\{\1\*?\}", blank, text, flags=re.S)
    text = re.sub(r"\$[^$\n]*\$", blank, text)
    text = re.sub(r"\\(?:eq)?ref\{[^}]*\}|\\cite[pt]?\{[^}]*\}", blank, text)
    text = re.sub(r"\[\d+(?:\s*[,–\-]\s*\d+)*\]", blank, text)                       # [12], [3–5]
    text = re.sub(r"\([A-Z][A-Za-z\-]+(?: et al\.?| and [A-Z][A-Za-z\-]+)?,? (?:19|20)\d\d[a-z]?(?:;[^)]*)?\)", blank, text)
    text = re.sub(r"\b10\.\d{4,9}/\S+|https?://\S+|doi:\S+", blank, text, flags=re.I)
    text = re.sub(r"`[^`\n]*`", blank, text)
    return text


def numerals(text):
    out = []
    for ln, line in enumerate(text.splitlines(), 1):
        if SKIP_LINE.match(line):
            continue
        for m in NUMERAL.finditer(line):
            before = line[:m.start()]
            if REF_CTX.search(before):
                continue
            if re.match(r"^\s*(\d+[.)]|\(\d+\))\s*$", line[:m.end() + 1]) and m.start() <= 2:
                continue  # list marker
            tok = m.group(0).replace("−", "-").replace(",", "")
            if re.match(r"^\d{1,2}\.\d{1,2}(\.\d+)?$", tok) and re.match(r"^\s*$", before):
                continue  # section number at line start
            out.append((ln, tok, line.strip()))
    return out


def matches(tok, numbers, tol):
    tok_clean = tok.lstrip("+")
    try:
        x = float(tok_clean)
    except ValueError:
        return None
    dec = len(tok_clean.split(".")[1]) if "." in tok_clean and "e" not in tok_clean.lower() else 0
    for k, e in numbers.items():
        v = e["value"]
        if isinstance(v, str):
            if v.strip() == tok_clean:
                return k
            continue
        if not isinstance(v, (int, float)):
            continue
        if render(e) == tok_clean or render(e).lstrip("+") == tok_clean:
            return k
        if abs(round(v, dec) - x) <= 1e-9 + tol * abs(v):
            return k
        if abs(v) >= 1000 and abs(v - x) <= 0.5 + tol * abs(v):  # "4663 tests" vs 4663.0
            return k
    return None


def cmd_fill(a):
    numbers = load_numbers(a.numbers)
    text = read_text(a.draft)
    missing = []

    def sub(m):
        k, f = m.group(1), m.group(2)
        if k not in numbers:
            missing.append(k)
            return m.group(0)
        return render(numbers[k], f)
    out = PLACEHOLDER.sub(sub, text)
    if missing:
        sys.exit("number_check fill: unknown keys (nothing guessed): " + ", ".join(sorted(set(missing))))
    pathlib.Path(a.out or a.draft).write_text(out, encoding="utf-8")
    print(f"filled {len(PLACEHOLDER.findall(text))} placeholders -> {a.out or a.draft}")


def cmd_check(a):
    numbers = load_numbers(a.numbers)
    allow = {s.strip() for s in (a.allow or "").split(",") if s.strip()}
    raw = read_text(a.draft)
    text = strip_protected(raw)
    unresolved = [m.group(1) for m in PLACEHOLDER.finditer(raw)]
    bad, used = [], set()
    for ln, tok, ctx in numerals(text):
        if tok in allow or (a.allow_years and YEAR.match(tok)):
            continue
        k = matches(tok, numbers, a.tol)
        if k:
            used.add(k)
        else:
            bad.append((ln, tok, ctx))
    unused = sorted(set(numbers) - used)
    lines = [f"# NUMBER_CHECK — {pathlib.Path(a.draft).name}", "",
             f"numbers file: `{a.numbers}` ({len(numbers)} keys); untraceable numerals: **{len(bad)}**; "
             f"unresolved placeholders: {len(unresolved)}; unused keys: {len(unused)}", ""]
    if bad:
        lines += ["## Untraceable numerals (must be generated into NUMBERS_USED.json or allowed explicitly)", "",
                  "| line | numeral | context |", "|---|---|---|"]
        lines += [f"| {ln} | `{tok}` | {ctx[:120].replace('|', '\\|')} |" for ln, tok, ctx in bad]
        lines.append("")
    if unresolved:
        lines += ["## Unresolved placeholders", ""] + [f"- {{{{{k}}}}}" for k in unresolved] + [""]
    if unused:
        lines += ["## Keys in NUMBERS_USED.json not used in the text", ""] + [f"- {k}" for k in unused] + [""]
    report = "\n".join(lines) + "\n"
    if a.report:
        pathlib.Path(a.report).write_text(report, encoding="utf-8")
    print(report)
    if bad or unresolved:
        sys.exit(1)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    f = sub.add_parser("fill")
    f.add_argument("draft")
    f.add_argument("--numbers", required=True)
    f.add_argument("--out", default=None)
    c = sub.add_parser("check")
    c.add_argument("draft")
    c.add_argument("--numbers", required=True)
    c.add_argument("--allow", default="", help="comma-separated numerals that need no entry (e.g. 0.3,95)")
    c.add_argument("--allow-years", action="store_true")
    c.add_argument("--tol", type=float, default=0.0, help="relative tolerance (default 0: exact after rounding)")
    c.add_argument("--report", default=None, help="write NUMBER_CHECK.md here")
    a = ap.parse_args()
    {"fill": cmd_fill, "check": cmd_check}[a.cmd](a)


if __name__ == "__main__":
    main()
